import React, { useState, useEffect, useRef } from 'react';
import Editor from '@monaco-editor/react';
import { VoiceCommand, VOICE_COMMANDS, SERVO_NAMES, HOME_ANGLES, PCA_CHANNEL_MAP } from '../types/simulation';
import { Code, Play, Square, Terminal, Trash2, FileText, Mic, Zap, Copy, ChevronDown } from 'lucide-react';

interface CodeSpaceIDEProps {
  onExecuteCommand: (cmd: VoiceCommand | string) => void;
  logs: string[];
  isRunning: boolean;
  onRunCode: (code: string) => void;
  onStopCode: () => void;
  onClearLogs: () => void;
  lastVoiceCommand?: string;
}

// Auto-generate detailed template code for every voice command
function generateCommandCode(cmd: string): string {
  const header = '// ============================================\n// Hash V3 Humanoid: "' + cmd + '" Sequence\n// Auto-generated by SimuForge Studio\n// ============================================\n';

  switch (cmd) {
    case 'Say Hi':
      return header + `async function sayHi() {
  robot.log("▶ Starting Say Hi greeting routine...");
  robot.log("  → PCA1 Ch10: R_Shoulder_Pitch = 180° (arm up)");
  robot.setServo("R_Shoulder_Pitch", 180);
  robot.setServo("R_Elbow_Pitch", 90);
  await robot.wait(500);

  for (let i = 0; i < 3; i++) {
    robot.log("  → Wave cycle " + (i+1) + "/3: R_Elbow_Pitch 60°↔120°");
    robot.setServo("R_Elbow_Pitch", 60);
    await robot.wait(350);
    robot.setServo("R_Elbow_Pitch", 120);
    await robot.wait(350);
  }

  robot.log("  → Returning all servos to HOME_ANGLES");
  robot.homePosition();
  robot.log("✅ Say Hi completed!");
}
sayHi();`;

    case 'Move Forward':
      return header + `async function moveForward(steps) {
  robot.log("▶ Starting forward walk: " + steps + " steps");
  robot.log("  Each step: weight shift → swing → plant");

  for (let step = 0; step < steps; step++) {
    const side = step % 2 === 0 ? "Right" : "Left";
    robot.log("  Step " + (step+1) + ": Shifting weight, swinging " + side + " leg");

    // 1. Shift weight
    robot.setServo("L_Hip_Roll", step % 2 === 0 ? 80 : 100);
    robot.setServo("R_Hip_Roll", step % 2 === 0 ? 80 : 100);
    await robot.wait(250);

    // 2. Swing leg forward
    const hipServo = step % 2 === 0 ? "R_Hip_Pitch" : "L_Hip_Pitch";
    const kneeServo = step % 2 === 0 ? "R_Knee_Pitch" : "L_Knee_Pitch";
    robot.log("  → " + hipServo + " = 65° (swing), " + kneeServo + " = 70° (bend)");
    robot.setServo(hipServo, 65);
    robot.setServo(kneeServo, 70);
    // Counter-swing arms
    robot.setServo("R_Shoulder_Pitch", step % 2 === 0 ? 30 : 0);
    robot.setServo("L_Shoulder_Pitch", step % 2 === 0 ? 150 : 180);
    await robot.wait(300);

    // 3. Plant foot
    robot.log("  → Plant foot: " + hipServo + " = 90°, " + kneeServo + " = 90°");
    robot.setServo(hipServo, 90);
    robot.setServo(kneeServo, 90);
    robot.setServo("R_Hip_Roll", 90);
    robot.setServo("L_Hip_Roll", 90);
    robot.setServo("R_Shoulder_Pitch", 0);
    robot.setServo("L_Shoulder_Pitch", 180);
    await robot.wait(200);
  }

  robot.homePosition();
  robot.log("✅ Walking " + steps + " steps completed!");
}
moveForward(4);`;

    case 'Move Backward':
      return header + `async function moveBackward(steps) {
  robot.log("▶ Starting backward walk: " + steps + " steps");
  for (let step = 0; step < steps; step++) {
    const side = step % 2 === 0 ? "Right" : "Left";
    robot.log("  Step " + (step+1) + ": Swing " + side + " leg backward");
    robot.setServo("L_Hip_Roll", step % 2 === 0 ? 80 : 100);
    robot.setServo("R_Hip_Roll", step % 2 === 0 ? 80 : 100);
    await robot.wait(250);
    const hip = step % 2 === 0 ? "R_Hip_Pitch" : "L_Hip_Pitch";
    const knee = step % 2 === 0 ? "R_Knee_Pitch" : "L_Knee_Pitch";
    robot.setServo(hip, 115);
    robot.setServo(knee, 55);
    await robot.wait(300);
    robot.setServo(hip, 90);
    robot.setServo(knee, 90);
    robot.setServo("R_Hip_Roll", 90);
    robot.setServo("L_Hip_Roll", 90);
    await robot.wait(200);
  }
  robot.homePosition();
  robot.log("✅ Backward walk completed!");
}
moveBackward(3);`;

    case 'Turn Left':
      return header + `async function turnLeft() {
  robot.log("▶ Turning left ~60°");
  robot.log("  → R_Hip_Yaw stays 90°, L_Hip_Yaw = 60° (rotate left)");
  robot.setServo("R_Hip_Yaw", 90);
  robot.setServo("L_Hip_Yaw", 60);
  await robot.wait(400);
  robot.log("  → Bring right foot: both = 60°");
  robot.setServo("R_Hip_Yaw", 60);
  await robot.wait(300);
  robot.log("  → Second step: L_Hip_Yaw = 30°");
  robot.setServo("L_Hip_Yaw", 30);
  await robot.wait(400);
  robot.setServo("R_Hip_Yaw", 30);
  await robot.wait(300);
  robot.homePosition();
  robot.log("✅ Turn Left completed!");
}
turnLeft();`;

    case 'Turn Right':
      return header + `async function turnRight() {
  robot.log("▶ Turning right ~60°");
  robot.setServo("R_Hip_Yaw", 120);
  robot.setServo("L_Hip_Yaw", 90);
  await robot.wait(400);
  robot.setServo("L_Hip_Yaw", 120);
  await robot.wait(300);
  robot.setServo("R_Hip_Yaw", 150);
  await robot.wait(400);
  robot.setServo("L_Hip_Yaw", 150);
  await robot.wait(300);
  robot.homePosition();
  robot.log("✅ Turn Right completed!");
}
turnRight();`;

    case 'Dance':
      return header + `async function dance() {
  robot.log("▶ 🕺 Starting dance routine!");
  robot.log("  Beat 1: Arms wide, sway right");
  robot.setServo("R_Shoulder_Pitch", 90); robot.setServo("L_Shoulder_Pitch", 90);
  robot.setServo("R_Shoulder_Roll", 45); robot.setServo("L_Shoulder_Roll", 135);
  robot.setServo("R_Hip_Roll", 70); robot.setServo("L_Hip_Roll", 70);
  await robot.wait(400);

  robot.log("  Beat 2: Arms up, sway left");
  robot.setServo("R_Shoulder_Pitch", 180); robot.setServo("L_Shoulder_Pitch", 0);
  robot.setServo("R_Hip_Roll", 110); robot.setServo("L_Hip_Roll", 110);
  await robot.wait(400);

  robot.log("  Beat 3-4: Bicep flex + twist");
  robot.setServo("R_Elbow_Pitch", 45); robot.setServo("R_Hip_Yaw", 70);
  await robot.wait(350);
  robot.setServo("L_Elbow_Pitch", 45); robot.setServo("L_Hip_Yaw", 110);
  await robot.wait(350);

  robot.log("  Beat 5: Squat pulse");
  robot.setServo("R_Knee_Pitch", 60); robot.setServo("L_Knee_Pitch", 60);
  await robot.wait(350);
  robot.setServo("R_Knee_Pitch", 90); robot.setServo("L_Knee_Pitch", 90);
  await robot.wait(250);

  robot.log("  Finale: Victory pose!");
  robot.setServo("R_Shoulder_Pitch", 180); robot.setServo("L_Shoulder_Pitch", 0);
  await robot.wait(800);
  robot.homePosition();
  robot.log("✅ Dance completed! 🎉");
}
dance();`;

    case 'Shake Hands':
      return header + `async function shakeHands() {
  robot.log("▶ Extending right arm for handshake");
  robot.setServo("R_Shoulder_Pitch", 90);
  robot.setServo("R_Elbow_Pitch", 45);
  await robot.wait(600);
  for (let i = 0; i < 3; i++) {
    robot.log("  Shake " + (i+1));
    robot.setServo("R_Elbow_Pitch", 55); await robot.wait(200);
    robot.setServo("R_Elbow_Pitch", 35); await robot.wait(200);
  }
  robot.homePosition();
  robot.log("✅ Shake Hands completed!");
}
shakeHands();`;

    case 'Hands Up':
      return header + `async function handsUp() {
  robot.log("▶ Both arms going up");
  robot.log("  → R_Shoulder_Pitch = 180° (up), L_Shoulder_Pitch = 0° (up)");
  robot.setServo("R_Shoulder_Pitch", 180);
  robot.setServo("L_Shoulder_Pitch", 0);
  robot.setServo("R_Elbow_Pitch", 90);
  robot.setServo("L_Elbow_Pitch", 90);
  await robot.wait(700);
  robot.log("✅ Hands Up — holding pose");
}
handsUp();`;

    case 'Hands Down':
      return header + `async function handsDown() {
  robot.log("▶ Lowering both arms to home");
  robot.setServo("R_Shoulder_Pitch", 0);  // Home for right
  robot.setServo("L_Shoulder_Pitch", 180); // Home for left
  robot.setServo("R_Elbow_Pitch", 90);
  robot.setServo("L_Elbow_Pitch", 90);
  await robot.wait(700);
  robot.log("✅ Hands Down completed!");
}
handsDown();`;

    case 'Bow':
      return header + `async function bow() {
  robot.log("▶ Bowing: Hip Pitch → 120°");
  robot.setServo("R_Hip_Pitch", 120);
  robot.setServo("L_Hip_Pitch", 120);
  await robot.wait(800);
  robot.log("  Holding bow...");
  await robot.wait(1000);
  robot.homePosition();
  robot.log("✅ Bow completed!");
}
bow();`;

    case 'Push Up':
      return header + `async function pushUp(reps) {
  robot.log("▶ Starting " + reps + " push-ups");
  robot.setServo("R_Hip_Pitch", 140); robot.setServo("L_Hip_Pitch", 140);
  robot.setServo("R_Shoulder_Pitch", 90); robot.setServo("L_Shoulder_Pitch", 90);
  robot.setServo("R_Elbow_Pitch", 90); robot.setServo("L_Elbow_Pitch", 90);
  await robot.wait(700);
  for (let i = 0; i < reps; i++) {
    robot.log("  Rep " + (i+1) + ": Down");
    robot.setServo("R_Elbow_Pitch", 30); robot.setServo("L_Elbow_Pitch", 30);
    await robot.wait(500);
    robot.log("  Rep " + (i+1) + ": Up");
    robot.setServo("R_Elbow_Pitch", 90); robot.setServo("L_Elbow_Pitch", 90);
    await robot.wait(500);
  }
  robot.homePosition();
  robot.log("✅ " + reps + " push-ups completed!");
}
pushUp(3);`;

    default:
      return header + `// This command uses the built-in animation engine.
// Trigger it via: robot voice command or the gesture grid.
robot.log("Executing: " + cmd);
// The kinematics engine handles the servo coordination.
// Each servo is driven by the PCA9685 at 50Hz PWM.
`;
  }
}

// Map voice commands to human-readable template names
const TEMPLATE_NAMES: Record<string, string> = {};
for (const cmd of VOICE_COMMANDS) {
  TEMPLATE_NAMES[cmd] = cmd;
}

export const CodeSpaceIDE: React.FC<CodeSpaceIDEProps> = ({
  onExecuteCommand,
  logs,
  isRunning,
  onRunCode,
  onStopCode,
  onClearLogs,
  lastVoiceCommand,
}) => {
  const [selectedTemplate, setSelectedTemplate] = useState('Say Hi');
  const [code, setCode] = useState(generateCommandCode('Say Hi'));
  const logsEndRef = useRef<HTMLDivElement>(null);

  const handleTemplateChange = (templateName: string) => {
    setSelectedTemplate(templateName);
    setCode(generateCommandCode(templateName));
  };

  // Auto-show code when voice command is triggered externally
  useEffect(() => {
    if (lastVoiceCommand && VOICE_COMMANDS.includes(lastVoiceCommand as any)) {
      setSelectedTemplate(lastVoiceCommand);
      setCode(generateCommandCode(lastVoiceCommand));
    }
  }, [lastVoiceCommand]);

  // Auto-scroll logs
  useEffect(() => {
    logsEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [logs]);

  return (
    <div className="h-64 w-full bg-[#111827] border-t border-[#1e293b] flex flex-col select-none shrink-0 overflow-hidden">
      {/* Tab bar header */}
      <div className="h-9 px-3 bg-[#0f172a] border-b border-[#1e293b] flex items-center justify-between shrink-0">
        <div className="flex items-center space-x-3">
          <div className="flex items-center space-x-1.5 text-xs font-semibold text-slate-300">
            <Code className="w-3.5 h-3.5 text-blue-400" />
            <span>CONTROLLER CODE SPACE (ESP32 RUNTIME)</span>
          </div>

          <div className="flex items-center space-x-1.5 bg-[#0a0e17] px-2 py-0.5 rounded border border-[#1e293b]">
            <FileText className="w-3 h-3 text-slate-400" />
            <select
              value={selectedTemplate}
              onChange={(e) => handleTemplateChange(e.target.value)}
              className="bg-transparent text-xs text-slate-300 focus:outline-none cursor-pointer"
            >
              {VOICE_COMMANDS.map((cmd) => (
                <option key={cmd} value={cmd} className="bg-[#111827]">
                  {cmd}
                </option>
              ))}
            </select>
            <ChevronDown className="w-3 h-3 text-slate-500" />
          </div>

          {lastVoiceCommand && (
            <div className="flex items-center space-x-1 px-2 py-0.5 bg-amber-500/10 border border-amber-500/30 rounded text-[10px] text-amber-300">
              <Mic className="w-3 h-3" />
              <span>Last: {lastVoiceCommand}</span>
            </div>
          )}
        </div>

        {/* Run / Stop Actions */}
        <div className="flex items-center space-x-2">
          {isRunning ? (
            <button
              onClick={onStopCode}
              className="flex items-center space-x-1 px-3 py-1 bg-rose-500/20 hover:bg-rose-500/30 text-rose-300 border border-rose-500/40 rounded text-xs font-semibold transition-all"
            >
              <Square className="w-3 h-3 fill-current" />
              <span>STOP</span>
            </button>
          ) : (
            <button
              onClick={() => onRunCode(code)}
              className="flex items-center space-x-1 px-3 py-1 bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-300 border border-emerald-500/40 rounded text-xs font-semibold transition-all"
            >
              <Play className="w-3 h-3 fill-current" />
              <span>RUN SCRIPT</span>
            </button>
          )}

          <button
            onClick={onClearLogs}
            title="Clear Console Output"
            className="p-1 text-slate-400 hover:text-white hover:bg-slate-800 rounded transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Editor & Console Split Body */}
      <div className="flex-1 flex overflow-hidden">
        {/* Left: Monaco Editor (65%) */}
        <div className="w-[65%] h-full border-r border-[#1e293b]">
          <Editor
            height="100%"
            defaultLanguage="javascript"
            value={code}
            onChange={(val) => setCode(val || '')}
            theme="vs-dark"
            options={{
              minimap: { enabled: false },
              fontSize: 12,
              lineNumbers: 'on',
              scrollBeyondLastLine: false,
              automaticLayout: true,
              tabSize: 2,
              fontFamily: "'JetBrains Mono', 'Fira Code', monospace",
              wordWrap: 'on',
            }}
          />
        </div>

        {/* Right: Serial Console & Telemetry (35%) */}
        <div className="w-[35%] h-full flex flex-col bg-[#0a0e17] overflow-hidden">
          <div className="h-6 px-3 bg-[#0d131f] border-b border-[#1e293b] flex items-center justify-between text-[11px] text-slate-400 font-mono">
            <div className="flex items-center space-x-1.5">
              <Terminal className="w-3 h-3 text-cyan-400" />
              <span>SERIAL MONITOR (115200 BAUD)</span>
            </div>
            <span className="text-[10px] text-emerald-400 font-mono">CONNECTED</span>
          </div>

          <div className="flex-1 p-2 font-mono text-[11px] overflow-y-auto space-y-0.5 text-slate-300 selection:bg-blue-500/30">
            {logs.length === 0 ? (
              <div className="text-slate-600 italic py-2">
                Serial console ready. Run code or trigger gestures to see telemetry.
              </div>
            ) : (
              logs.map((log, idx) => (
                <div key={idx} className="leading-relaxed">
                  <span className="text-slate-600 select-none mr-1">{'>'}</span>
                  {log.includes('✅') || log.includes('complete') || log.includes('finished') ? (
                    <span className="text-emerald-400">{log}</span>
                  ) : log.includes('▶') || log.includes('Starting') || log.includes('Executing') ? (
                    <span className="text-cyan-300">{log}</span>
                  ) : log.includes('→') || log.includes('PCA') || log.includes('Ch') ? (
                    <span className="text-blue-300">{log}</span>
                  ) : log.includes('⚠') || log.includes('error') || log.includes('Error') ? (
                    <span className="text-rose-400">{log}</span>
                  ) : log.includes('🚨') || log.includes('EMERGENCY') ? (
                    <span className="text-rose-500 font-bold">{log}</span>
                  ) : log.includes('Voice Command') ? (
                    <span className="text-amber-300">{log}</span>
                  ) : log.includes('Servo') || log.includes('servo') ? (
                    <span className="text-violet-300">{log}</span>
                  ) : (
                    <span>{log}</span>
                  )}
                </div>
              ))
            )}
            <div ref={logsEndRef} />
          </div>
        </div>
      </div>
    </div>
  );
};

export default CodeSpaceIDE;
